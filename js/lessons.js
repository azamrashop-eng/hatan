// SafeStorage utility to fallback to in-memory store if localStorage is blocked by browser policies on local files
const SafeStorage = {
    _data: {},
    getItem(key) {
        try {
            return localStorage.getItem(key);
        } catch (e) {
            console.warn("Storage read failed, using memory:", e);
            return this._data[key] || null;
        }
    },
    setItem(key, value) {
        try {
            localStorage.setItem(key, value);
        } catch (e) {
            console.warn("Storage write failed, using memory:", e);
            this._data[key] = String(value);
        }
    },
    removeItem(key) {
        try {
            localStorage.removeItem(key);
        } catch (e) {
            console.warn("Storage delete failed, using memory:", e);
            delete this._data[key];
        }
    }
};

